"""Shared setup for experiments: config, device, data, calibrated mixed model, output paths.

Output layout (``results/`` by default)::

    accuracy/                hardware-independent (computed once, usually on Kaggle)
        reference.json       FP32 / all-FP16 / all-INT8 accuracies, seconds per evaluation
        accuracy_table.csv   all 1,024 configs on the val subset
        sensitivity.csv      Experiment 1 (full validation split)
        final_test.csv       held-out test accuracy of the selected configs
    <gpu>/                   one folder per GPU, e.g. rtx3050ti/, t4/
        lut.csv              per-unit latency table, all batch sizes
        search_results.csv   Experiments 2-5 (all methods x batch sizes x budgets)
        random_curve.csv     Experiment 2 (random-search quality vs evaluations)
        verify.csv           Experiment 6 (LUT estimate vs real full-model latency)
    figures/  tables/        generated by `precisionpilot report`
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import torch

from precisionpilot.data import CifarData, build_data
from precisionpilot.model import UnitResNet, load_model
from precisionpilot.precision import MixedPrecisionModel, build_mixed_model
from precisionpilot.utils import ensure_dir, get_device, gpu_slug, set_seed


@dataclass
class Workspace:
    cfg: object
    device: torch.device
    data: CifarData
    model: UnitResNet
    mm: MixedPrecisionModel
    results: Path
    fake: bool = False

    @property
    def accuracy_dir(self) -> Path:
        return ensure_dir(self.results / "accuracy")

    def gpu_dir(self, slug: str) -> Path:
        return ensure_dir(self.results / slug)

    @property
    def image_size(self) -> int:
        return self.cfg.data.image_size

    @property
    def batch_size(self) -> int:
        return self.cfg.data.eval_batch_size


def make_workspace(cfg, device: str | None = "auto", fake: bool = False,
                   need_model: bool = True, fake_size: str = "normal") -> Workspace:
    set_seed(cfg.seed)
    dev = get_device(device)
    data = build_data(cfg, fake=fake, fake_size=fake_size)
    model = mm = None
    if need_model:
        model, _ = load_model(cfg, "cpu", allow_random=fake)
        calib_x, _ = data.get("calib")
        mm = build_mixed_model(model, cfg, calib_x, dev)
        model = model.to(dev)
    return Workspace(cfg=cfg, device=dev, data=data, model=model, mm=mm,
                     results=ensure_dir(cfg.path("results_dir")), fake=fake)


def resolve_gpu_slug(backend_device_name: str, override: str | None = None) -> str:
    return override or gpu_slug(backend_device_name)
